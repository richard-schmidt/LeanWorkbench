#!/usr/bin/env python3
"""Generate src/leanwb/AbbrevTable.kt from fixtures/abbreviations.json.

The JSON is Lean's own `\\`-abbreviation table, as the VS Code extension ships it:
https://github.com/leanprover/vscode-lean4, lean4-unicode-input/src/abbreviations.json
(Apache-2.0), commit 00a05fe2a7076e431cad7af1ad24cd14452145d0.

Kept in Kotlin source, not an Android asset, so the host tests see the same table
the app uses. Entries are split across several string constants: one class-file
constant holds at most 65535 bytes. Names with a space or a backslash cannot be
typed as `\\name` and are left out.
"""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
table = json.load(open(os.path.join(root, "fixtures", "abbreviations.json"), encoding="utf-8"))
entries = [(k, v) for k, v in table.items() if not any(c.isspace() or c == "\\" for c in k)]
for k, v in entries:
    assert "\t" not in k + v and "\n" not in k + v


def lit(s):
    return ('"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
            .replace("\n", "\\n").replace("\t", "\\t") + '"')


chunks, cur = [], []
for k, v in entries:
    cur.append(k + "\t" + v)
    if len(cur) == 300:
        chunks.append(cur); cur = []
if cur:
    chunks.append(cur)
out = ["// Generated by tools/gen_abbrev.py from fixtures/abbreviations.json. Do not edit.",
       "// Lean's abbreviation table (leanprover/vscode-lean4, Apache-2.0).",
       "package leanwb", "",
       "internal object AbbrevTable {",
       f"    /** {len(entries)} entries, `name<TAB>symbol` per line; `$CURSOR` marks where the cursor goes. */",
       "    val chunks: List<String> = listOf("]
for c in chunks:
    out.append("        " + lit("\n".join(c)) + ",")
out += ["    )", "}", ""]
open(os.path.join(root, "src", "leanwb", "AbbrevTable.kt"), "w", encoding="utf-8").write("\n".join(out))
print(len(entries), "entries in", len(chunks), "chunks")
